import sys
input = sys.stdin.readline

size = int(input())
budgets = list(map(int, input().split()))
total = int(input())

# 모든 요청 합이 총예산 이하면 최대 요청액이 상한액
if sum(budgets) <= total:
    print(max(budgets))
else:
    lo = 1
    hi = max(budgets)
    answer = 0

    while lo <= hi:
        mid = (lo + hi) // 2 # 정답 후보값

        # mid를 상한액으로 가정하고 전체 배정액 계산
        allocated = sum(min(b, mid) for b in budgets)

        if allocated <= total: # 가능 → 더 큰 값 탐색
            answer = mid
            lo = mid + 1
        else: # 불가능 → 더 작은 값 탐색
            hi = mid - 1
    
    print(answer)


